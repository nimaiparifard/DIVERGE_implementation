"""
Parse this repo's already-cached LLM node-classification responses
(`datasets/gpt_4o/cora.json`, `datasets/PubMed/{i}.json`) into a ranked list of
predicted labels per node -- the "Ranked Predictions" half of TAPE's prompt output
(paper Section 4.1). The full raw response text is used as-is for h_expl (that is
already what `dataset.dataset_loader.load_gpt_enhanced_explanations` returns, and
what `used_llm_responses=True` feeds to LM_expl finetuning); this module only
extracts the *label ranking* needed for h_pred (Eq. 5).

Two response formats are present in this repo's cached data:
  1) Cora's cache follows the paper's exact prompt (Table 5) closely: an explicit
     "Answer: LabelA, LabelB" line, with label names matching the dataset's
     `label_name` list verbatim.
  2) PubMed's cache predates this paper's exact prompt wording (it was generated by
     an earlier "gpt-3.5-turbo-0301" pipeline in this repo) and has no "Answer:"
     line -- just free text that mentions a diabetes-type phrase inline. We fall
     back to ranking by order of first mention, matched against dataset-specific
     phrase aliases (PubMed's `label_name` strings, e.g. "Diabetes Mellitus Type 1",
     don't literally appear in the cached text, which instead says "Type 1
     diabetes" -- the wording from this paper's own prompt design).
"""
import re

# Phrases the cached LLM responses actually use, mapped to each dataset's real
# label_name strings. Only needed where they diverge (Cora's label_name strings
# already appear verbatim in its cache).
LABEL_ALIASES = {
    "pubmed": {
        "Experimental": ["experimentally induced diabetes", "experimental diabetes", "experimental"],
        "Diabetes Mellitus Type 1": ["type 1 diabetes", "type i diabetes", "type 1"],
        "Diabetes Mellitus Type 2": ["type 2 diabetes", "type ii diabetes", "type 2"],
    },
}


def _normalize(text):
    return text.replace("_", " ").strip().lower()


def _match_label(candidate, label_names, aliases):
    candidate_norm = _normalize(candidate)
    for label in label_names:
        if _normalize(label) == candidate_norm:
            return label
    for label in label_names:
        for phrase in aliases.get(label, [_normalize(label)]):
            if phrase in candidate_norm or candidate_norm in phrase:
                return label
    return None


def parse_llm_response(raw_text, label_names, dataset_name=None):
    """Returns (ranked_predictions: list[str] of label_names, explanation_text: str)."""
    raw_text = raw_text or ""
    aliases = LABEL_ALIASES.get(dataset_name, {})

    predictions = []
    match = re.search(r"Answer:\s*(.+)", raw_text)
    if match:
        first_line = match.group(1).split("\n")[0]
        for candidate in first_line.split(","):
            label = _match_label(candidate, label_names, aliases)
            if label and label not in predictions:
                predictions.append(label)

    if not predictions:
        # Fallback: rank by position of first mention in the free-form text.
        lower_text = raw_text.lower()
        positions = []
        for label in label_names:
            best_pos = None
            for phrase in aliases.get(label, [_normalize(label)]):
                pos = lower_text.find(phrase)
                if pos != -1 and (best_pos is None or pos < best_pos):
                    best_pos = pos
            if best_pos is not None:
                positions.append((best_pos, label))
        positions.sort(key=lambda x: x[0])
        predictions = [label for _, label in positions]

    return predictions, raw_text
